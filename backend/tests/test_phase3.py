@pytest.mark.asyncio
async def test_api_exam_generation_and_full_lifecycle():
    await init_db()

    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        # 1. First upload a test document to serve as grounding source
        doc_content = create_sample_pdf_bytes()
        upload_res = await client.post(
            "/api/documents/upload",
            files={"file": ("Cell_Biology_101.pdf", doc_content, "application/pdf")},
        )
        assert upload_res.status_code == 201
        doc_id = upload_res.json()["id"]

        # 2. Generate multi-group exam
        exam_payload = {
            "document_id": doc_id,
            "title": "Cell Biology Midterm Examination 2026",
            "subject": "Molecular Biology",
            "institution": "Faculty of Sciences",
            "teacher_name": "Prof. Harrison",
            "grade_level": "Undergraduate Year 2",
            "duration_minutes": 90,
            "total_marks": 100.0,
            "language": "en",
            "is_rtl": False,
            "bloom_enabled": True,
            "groups_count": 2,  # Group A & Group B
            "difficulty_distribution": {"easy": 40, "medium": 40, "hard": 20},
            "question_types_config": {
                "mcq": 2,
                "true_false": 1,
                "short_answer": 1,
                "fill_blank": 0,
                "essay": 0,
            },
        }

        gen_res = await client.post("/api/exams/generate", json=exam_payload)
        assert gen_res.status_code == 201
        exam_data = gen_res.json()

        exam_id = exam_data["id"]
        assert exam_data["title"] == "Cell Biology Midterm Examination 2026"
        assert exam_data["groups_count"] == 2
        assert len(exam_data["groups"]) == 2

        group_a = exam_data["groups"][0]
        group_b = exam_data["groups"][1]
        assert group_a["group_name"] == "Group A"
        assert group_b["group_name"] == "Group B"

        # Check questions in Group A
        assert len(group_a["questions"]) >= 3
        q1 = group_a["questions"][0]
        # Strict provenance validation
        assert q1["source_document_name"] is not None
        assert q1["source_page"] >= 1
        assert len(q1["source_evidence"]) > 5

        # 3. Retrieve Exam by ID
        get_res = await client.get(f"/api/exams/{exam_id}")
        assert get_res.status_code == 200
        assert get_res.json()["id"] == exam_id

        # 4. Retrieve Answer Keys
        key_res = await client.get(f"/api/exams/{exam_id}/answer-key")
        assert key_res.status_code == 200
        keys_data = key_res.json()
        assert len(keys_data) == 2  # Answer key for both Group A and Group B
        assert keys_data[0]["group_name"] == "Group A"
        assert len(keys_data[0]["items"]) >= 3

        # 5. Teacher Edits a Question
        q_id = q1["id"]
        edit_payload = {
            "question_text": "Updated Question: What is the primary function of the cell nucleus?",
            "marks": 2.5,
        }
        put_res = await client.put(f"/api/exams/{exam_id}/questions/{q_id}", json=edit_payload)
        assert put_res.status_code == 200
        updated_q = put_res.json()
        assert updated_q["question_text"] == "Updated Question: What is the primary function of the cell nucleus?"
        assert updated_q["marks"] == 2.5

        # 6. List Exams
        list_res = await client.get("/api/exams")
        assert list_res.status_code == 200
        all_exams = list_res.json()
        assert any(e["id"] == exam_id for e in all_exams)

        # 7. Delete Exam
        del_res = await client.delete(f"/api/exams/{exam_id}")
        assert del_res.status_code == 204

        # Verify deletion
        verify_res = await client.get(f"/api/exams/{exam_id}")
        assert verify_res.status_code == 404


