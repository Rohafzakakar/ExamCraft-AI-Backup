def test_json_extraction_from_llm_responses():
    # 1. Plain JSON string
    data1 = extract_json_from_llm_response('{"status": "ok", "count": 42}')
    assert data1["status"] == "ok"
    assert data1["count"] == 42

    # 2. Markdown fenced block
    fenced = "Here is the exam:\n```json\n{\"exam\": \"Midterm\", \"groups\": [\"A\", \"B\"]}\n```\nHope this helps!"
    data2 = extract_json_from_llm_response(fenced)
    assert data2["exam"] == "Midterm"
    assert "A" in data2["groups"]

    # 3. Trailing commas recovery
    trailing = '{"items": ["q1", "q2",], "total": 2,}'
    data3 = extract_json_from_llm_response(trailing)
    assert len(data3["items"]) == 2

    # 4. JSON Array extraction
    arr_str = 'Generated questions: [{"id": 1}, {"id": 2}]'
    data4 = extract_json_from_llm_response(arr_str)
    assert isinstance(data4, list)
    assert len(data4) == 2


