@pytest.mark.asyncio
async def test_isomorphic_variant_generation_integrity():
    generator = ExamGenerationService()

    base_q = [
        {
            "question_number": 1,
            "question_type": "mcq",
            "question_text": "What is the capital of France?",
            "options": ["Paris", "Berlin", "Rome", "Madrid"],
            "correct_answer": "Paris",
            "marks": 2.0,
            "difficulty": "easy",
            "source_document_name": "Geography.pdf",
            "source_page": 1,
            "source_evidence": "Paris is the capital of France.",
        },
        {
            "question_number": 2,
            "question_type": "mcq",
            "question_text": "What is the chemical symbol for Gold?",
            "options": ["Au", "Ag", "Fe", "Cu"],
            "correct_answer": "Au",
            "marks": 2.0,
            "difficulty": "medium",
            "source_document_name": "Chemistry.pdf",
            "source_page": 4,
            "source_evidence": "Gold is represented by symbol Au.",
        },
    ]

    # Generate Group B isomorphic variant
    variant_q = generator._create_isomorphic_variant_group(base_q, "Group B")

    assert len(variant_q) == len(base_q)
    # Order was permuted for anti-cheating
    assert variant_q[0]["question_text"] != base_q[0]["question_text"]

    # Verify options permutation and answer correctness preservation
    for vq in variant_q:
        orig = next(b for b in base_q if b["question_text"] == vq["question_text"])
        # Same set of options
        assert set(vq["options"]) == set(orig["options"])
        # Correct answer still points to the correct term
        assert orig["correct_answer"] in vq["correct_answer"]


